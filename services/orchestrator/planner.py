"""Task Planner: Decomposes complex user requests into structured execution steps."""

import json
from pathlib import Path
import re
from typing import Any

from packages.shared_schemas.models import Message, RiskLevel, TaskPlanStep
from services.model_gateway.registry import ModelRegistry
from services.tools.registry import ToolRegistry


def _generate_file_content(path: str, topic: str, prompt: str) -> str:
    """Generate high-quality initial structured template content for newly created files."""
    ext = Path(path).suffix.lower()
    lower_topic = topic.lower()
    lower_prompt = prompt.lower()

    if ext == ".md":
        if any(w in lower_topic or w in lower_prompt for w in ["calc", "catculat", "math"]):
            return (
                "# Calculator Project\n\n"
                "## Overview\n"
                "A modular, local-first calculation engine and utility designed for Zevon.\n\n"
                "## Key Features\n"
                "- **Basic Arithmetic**: Addition (`+`), Subtraction (`-`), Multiplication (`*`), Division (`/`)\n"
                "- **Advanced Operations**: Exponents (`^`), Square roots (`sqrt`), Modulo (`%`), Parentheses\n"
                "- **Safe Evaluation**: Sandboxed AST validation preventing dangerous arbitrary code execution\n"
                "- **Zero Cloud Dependencies**: 100% offline, local-first execution\n\n"
                "## Quick Start & Usage\n"
                "```python\n"
                "from services.tools.builtin import CalculatorTool\n\n"
                "calc = CalculatorTool()\n"
                "# Safe evaluation\n"
                "result = 78 * 89\n"
                "print(f'Result: {result}')\n"
                "```\n\n"
                "## Operations Reference\n"
                "| Operation | Expression | Result |\n"
                "| :--- | :--- | :--- |\n"
                "| Addition | `12 + 8` | `20` |\n"
                "| Multiplication | `15 * 3` | `45` |\n"
                "| Product | `78 * 89` | `6942` |\n\n"
                "---\n"
                "*Created autonomously by Zevon Task Orchestrator.*\n"
            )
        elif "readme" in lower_topic or "readme" in lower_prompt:
            return (
                "# Project Overview\n\n"
                "## Description\n"
                f"Documentation for {topic or 'the project'} generated by Zevon.\n\n"
                "## Installation & Verification\n"
                "Run test suites and linters to verify workspace readiness:\n"
                "```bash\n"
                "pytest tests -v\n"
                "ruff check .\n"
                "```\n"
            )
        else:
            title = topic.replace("_", " ").title() if topic else "Project Documentation"
            return (
                f"# {title}\n\n"
                "## Overview\n"
                f"Structured documentation generated for request: *{prompt}*.\n\n"
                "## Specifications\n"
                "- **Status**: Active\n"
                "- **Environment**: Local-First Zevon Assistant\n"
                "- **Persistence**: Local SQLite & Authorized File Workspace\n"
            )
    elif ext == ".py":
        mod_name = topic or "module"
        return (
            f"# {Path(path).name}\n"
            f"# Generated by Zevon Task Orchestrator for: {prompt}\n\n"
            "def main():\n"
            f"    print('Running {mod_name}...')\n\n"
            "if __name__ == '__main__':\n"
            "    main()\n"
        )
    elif ext == ".json":
        return json.dumps({"project": topic or "zevon-task", "status": "active", "generated_for": prompt}, indent=2)
    else:
        return f"# {topic or 'Document'}\nGenerated by Zevon for: {prompt}\n"


class TaskPlanner:
    """
    Analyzes user prompts, identifies goals and dependencies,
    and produces an ordered list of TaskPlanSteps with assigned tools and risk levels.
    """

    def __init__(self, tool_registry: ToolRegistry, model_gateway: ModelRegistry | None = None):
        self.tool_registry = tool_registry
        self.model_gateway = model_gateway

    async def plan(self, prompt: str, context: dict[str, Any] | None = None) -> list[TaskPlanStep]:
        """
        Generate execution plan for a user prompt.
        Prioritizes high-confidence heuristic decomposition for instant, deterministic execution,
        falling back to LLM-based planning when prompt requires general reasoning.
        """
        heuristic_steps = self._plan_heuristic(prompt)
        # If heuristic identified a specific action (not the generic fallback web_research), use it immediately:
        if heuristic_steps and not (
            len(heuristic_steps) == 1 and heuristic_steps[0].tool_name == "web_research"
        ):
            return heuristic_steps

        if self.model_gateway:
            try:
                import asyncio

                llm_plan = await asyncio.wait_for(self._plan_with_llm(prompt), timeout=8.0)
                if llm_plan:
                    return llm_plan
            except Exception:
                pass  # Fall back to heuristic decomposition

        return heuristic_steps

    async def _plan_with_llm(self, prompt: str) -> list[TaskPlanStep] | None:
        """Attempt to decompose task using active local LLM."""
        if not self.model_gateway:
            return None

        # Check provider health
        health = await self.model_gateway.check_health()
        if health.get("mode") == "offline" or not health.get("providers", {}).get("ollama", False):
            return None

        tools_summary = [
            f"- {t.name} ({t.risk_level.value}): {t.description}"
            for t in self.tool_registry.list_tools()
        ]
        system_prompt = (
            "You are Zevon's Task Planning Engine. Decompose the user's request into 1 to 5 sequential execution steps.\n"
            f"Available tools:\n{chr(10).join(tools_summary)}\n\n"
            "Respond ONLY with a valid JSON array of objects with keys:\n"
            '  "title": str,\n'
            '  "tool_name": str or null,\n'
            '  "arguments": dict of arguments,\n'
            '  "risk_level": "R0", "R1", "R2", or "R3"\n'
        )
        messages = [
            Message(conversation_id="planner", role="system", content=system_prompt),
            Message(conversation_id="planner", role="user", content=f"User request: {prompt}\nPlan steps JSON:"),
        ]
        response_text = ""
        try:
            async for chunk in self.model_gateway.stream_chat(messages, temperature=0.1):
                response_text += chunk
        except Exception:
            return None

        # Extract JSON array
        match = re.search(r"\[\s*\{.*\}\s*\]", response_text, re.DOTALL)
        if match:
            try:
                raw_steps = json.loads(match.group(0))
                steps = []
                for i, s in enumerate(raw_steps, 1):
                    tool_name = s.get("tool_name")
                    tool = self.tool_registry.get_tool(tool_name) if tool_name else None
                    risk_str = s.get("risk_level", tool.risk_level.value if tool else "R0")
                    try:
                        risk = RiskLevel(risk_str)
                    except ValueError:
                        risk = tool.risk_level if tool else RiskLevel.R0
                    steps.append(
                        TaskPlanStep(
                            step_id=i,
                            title=s.get("title", f"Step {i}"),
                            tool_name=tool_name,
                            arguments=s.get("arguments", {}),
                            risk_level=risk,
                            status="pending",
                        )
                    )
                if steps:
                    return steps
            except Exception:
                pass
        return None

    def _plan_heuristic(self, prompt: str) -> list[TaskPlanStep]:
        """Heuristic planner decomposing common multi-step and single-step requests."""
        lower = prompt.lower().strip()
        alpha_lower = re.sub(r"[^a-z0-9]", "", lower)
        steps: list[TaskPlanStep] = []

        # 1. Multi-step: "calculate ... and write/save to ..."
        if ("calculate" in lower or re.search(r"\d+[\s\+\-\*\/\^]+\d+", lower)) and (
            "write" in lower or "save" in lower
        ):
            calc_match = re.search(r"calculate\s+([^\s,;]+(?:\s*[\+\-\*\/]\s*[^\s,;]+)*)", prompt, re.I)
            expr = calc_match.group(1) if calc_match else "10 + 20"
            file_match = re.search(r"(?:to|file)\s+([a-zA-Z0-9_\-\.\/\\:]+\.[a-zA-Z0-9]+)", prompt, re.I)
            target_file = file_match.group(1) if file_match else "calc_result.txt"

            steps.append(
                TaskPlanStep(
                    step_id=1,
                    title=f"Calculate expression: {expr}",
                    tool_name="calculator",
                    arguments={"expression": expr},
                    risk_level=RiskLevel.R0,
                    status="pending",
                )
            )
            steps.append(
                TaskPlanStep(
                    step_id=2,
                    title=f"Save result to {target_file}",
                    tool_name="file_write",
                    arguments={"path": target_file, "content": "Calculated Result"},
                    risk_level=RiskLevel.R1,
                    status="pending",
                )
            )
            return steps

        # 2. Multi-step: "research ... and save note / save file"
        if ("research" in lower or "find out" in lower) and ("note" in lower or "save" in lower):
            topic = re.sub(r"(research|find out|and save.*)", "", prompt, flags=re.I).strip() or "General inquiry"
            steps.append(
                TaskPlanStep(
                    step_id=1,
                    title=f"Research topic: {topic}",
                    tool_name="web_research",
                    arguments={"query": topic},
                    risk_level=RiskLevel.R0,
                    status="pending",
                )
            )
            steps.append(
                TaskPlanStep(
                    step_id=2,
                    title=f"Record notes on {topic}",
                    tool_name="notes",
                    arguments={"action": "create", "title": f"Notes on {topic}", "content": f"Research on {topic}"},
                    risk_level=RiskLevel.R1,
                    status="pending",
                )
            )
            return steps

        # 3. File delete (R2 action - requires approval)
        delete_keywords = ["delete", "remove", "erase", "dlete", "rm"]
        has_delete = any(k in lower for k in delete_keywords) or any(
            k in alpha_lower for k in ["deletefile", "dletefile", "dleteafile", "removefile", "erasefile"]
        )
        if has_delete:
            file_match = re.search(r"([a-zA-Z0-9_\-\.\/\\:]+\.[a-zA-Z0-9]+)", prompt)
            path = file_match.group(1) if file_match else "temp.txt"
            return [
                TaskPlanStep(
                    step_id=1,
                    title=f"Delete file '{path}'",
                    tool_name="file_delete",
                    arguments={"path": path},
                    risk_level=RiskLevel.R2,
                    status="pending",
                )
            ]

        # 4. File write / creation (R1 action)
        create_keywords = ["create", "write", "make", "generate", "save", "touch", "new"]
        file_type_keywords = ["file", "md", "markdown", "readme", "document", "doc", "script"]
        has_create = any(k in lower for k in create_keywords) or any(
            k in alpha_lower for k in ["createmd", "createfile", "writemd", "writefile", "makefile", "touchfile"]
        )
        has_file = any(k in lower for k in file_type_keywords) or any(
            k in alpha_lower for k in ["file", "mdfile", "markdown", "readme"]
        )
        has_ext = bool(re.search(r"([a-zA-Z0-9_\-\.\/\\:]+\.(?:md|txt|py|json|html|js|csv|yaml|yml))", prompt, re.I))

        if (has_create and (has_file or has_ext)) or ("createmd" in alpha_lower or "createfile" in alpha_lower):
            # Extract target path and topic
            file_match = re.search(r"([a-zA-Z0-9_\-\.\/\\:]+\.(?:md|txt|py|json|html|js|csv|yaml|yml))", prompt, re.I)
            if file_match:
                path = file_match.group(1)
                topic = Path(path).stem
            else:
                if any(k in alpha_lower for k in ["calculator", "catculat", "calc"]):
                    topic = "calculator"
                elif "readme" in alpha_lower:
                    topic = "README"
                else:
                    topic_match = re.search(r"(?:for|about|named|called)\s+([a-zA-Z0-9_\-]+)", prompt, re.I)
                    topic = topic_match.group(1) if topic_match else "document"

                ext = ".md" if ("md" in alpha_lower or "markdown" in lower) else (".py" if "python" in lower or "script" in lower else ".md")
                path = f"{topic}{ext}"

            content = _generate_file_content(path, topic, prompt)
            return [
                TaskPlanStep(
                    step_id=1,
                    title=f"Write file '{path}'",
                    tool_name="file_write",
                    arguments={"path": path, "content": content},
                    risk_level=RiskLevel.R1,
                    status="pending",
                )
            ]

        # 5. File read (R0)
        if any(k in lower for k in ["read file", "open file", "inspect file", "show content of", "cat file", "view file"]) or any(
            k in alpha_lower for k in ["readfile", "openfile", "viewfile"]
        ):
            file_match = re.search(r"([a-zA-Z0-9_\-\.\/\\:]+\.[a-zA-Z0-9]+)", prompt)
            path = file_match.group(1) if file_match else "README.md"
            return [
                TaskPlanStep(
                    step_id=1,
                    title=f"Read file '{path}'",
                    tool_name="file_read",
                    arguments={"path": path},
                    risk_level=RiskLevel.R0,
                    status="pending",
                )
            ]

        # 6. File search (R0)
        if any(k in lower for k in ["find file", "search file", "locate file", "list files"]) or any(
            k in alpha_lower for k in ["findfile", "searchfile", "listfiles"]
        ):
            pattern_match = re.search(r"(\*\.[a-zA-Z0-9]+|[a-zA-Z0-9_\-\*]+\.[a-zA-Z0-9]+)", prompt)
            pattern = pattern_match.group(1) if pattern_match else "*"
            return [
                TaskPlanStep(
                    step_id=1,
                    title=f"Search files matching '{pattern}'",
                    tool_name="file_search",
                    arguments={"pattern": pattern},
                    risk_level=RiskLevel.R0,
                    status="pending",
                )
            ]

        # 7. Calculator / Math (R0)
        if "calculate" in lower or re.search(r"^\s*[\d\(\)\.\s\+\-\*\/\^]+\s*$", prompt):
            expr_match = re.search(r"calculate\s+(.+)$", prompt, re.I)
            expr = expr_match.group(1).strip() if expr_match else prompt.strip()
            return [
                TaskPlanStep(
                    step_id=1,
                    title=f"Calculate: {expr}",
                    tool_name="calculator",
                    arguments={"expression": expr},
                    risk_level=RiskLevel.R0,
                    status="pending",
                )
            ]

        # 8. Time / Date (R0)
        if any(k in lower for k in ["what time", "current time", "what date", "today's date", "timestamp"]):
            return [
                TaskPlanStep(
                    step_id=1,
                    title="Retrieve current date and time",
                    tool_name="current_time",
                    arguments={"timezone": "local"},
                    risk_level=RiskLevel.R0,
                    status="pending",
                )
            ]

        # 9. Code execution (R1)
        if any(k in lower for k in ["run python", "execute code", "run code", "run script"]):
            return [
                TaskPlanStep(
                    step_id=1,
                    title="Execute Python snippet",
                    tool_name="code_execution",
                    arguments={"code": "print('Code executed successfully.')"},
                    risk_level=RiskLevel.R1,
                    status="pending",
                )
            ]

        # 10. App launch (R1)
        if any(k in lower for k in ["launch", "open app", "start app"]):
            app = "calculator"
            for candidate in ["calculator", "notepad", "terminal"]:
                if candidate in lower:
                    app = candidate
                    break
            return [
                TaskPlanStep(
                    step_id=1,
                    title=f"Launch application '{app}'",
                    tool_name="app_launch",
                    arguments={"app_name": app},
                    risk_level=RiskLevel.R1,
                    status="pending",
                )
            ]

        # 11. Notes (R0 / R1)
        if "note" in lower:
            action = "create" if any(w in lower for w in ["create", "add", "take", "write", "save"]) else "list"
            return [
                TaskPlanStep(
                    step_id=1,
                    title=f"Notes: {action}",
                    tool_name="notes",
                    arguments={"action": action, "title": prompt[:30], "content": prompt},
                    risk_level=RiskLevel.R1 if action == "create" else RiskLevel.R0,
                    status="pending",
                )
            ]

        # 12. Default web research / synthesis (R0)
        return [
            TaskPlanStep(
                step_id=1,
                title=f"Research and answer: {prompt[:40]}",
                tool_name="web_research",
                arguments={"query": prompt},
                risk_level=RiskLevel.R0,
                status="pending",
            )
        ]
